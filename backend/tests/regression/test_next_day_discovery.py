@pytest.mark.asyncio
async def test_tottori_iwami_missing_family_recovered_even_when_primary_exists():
    local = sample('ＪＲ山陰本線', '2026-11-04', '22:10', '22:36')
    tomorrow_local = sample('ＪＲ山陰本線', '2026-11-05', '05:23', '05:45', total_duration='22m')
    hamakaze = sample('ＪＲ特急はまかぜ4号', '2026-11-05', '12:56', '13:12')
    # Explicit end-of-service evidence is generated by setup_search; the adaptive
    # six-candidate frontier is exercised in test_operating_family_discovery.
    service, provider, cache = setup_search([local], [tomorrow_local, hamakaze])
    routes = await service.search(request())
    assert len(routes) == 2
    assert {r.id for r in routes} == {local.id, hamakaze.id}
    chosen = next(r for r in routes if 'はまかぜ' in r.segments[0].railway_name_jp)
    payload = RouteResponseSchema(**chosen.model_dump()).model_dump()
    assert payload['search_date'] == '2026-11-05'
    assert payload['departure_datetime'] == '2026-11-05T12:56:00+09:00'
    assert chosen.total_duration == '16m'
    assert chosen.transfer_count == 0 and len(chosen.passenger_legs) == 1
    assert chosen.result_kind == 'requested'  # one existing result collection
    assert (await cache.get(chosen.id)).search_date == '2026-11-05'
    assert [(c.kwargs['date'], c.kwargs['time']) for c in provider.search_routes.await_args_list] == [
        ('2026-11-04', '22:00'), ('2026-11-04', '05:00'), ('2026-11-04', '12:57'),
        ('2026-11-04', '22:11'), ('2026-11-05', '05:00')]
    provider.get_timetable.assert_not_awaited()


