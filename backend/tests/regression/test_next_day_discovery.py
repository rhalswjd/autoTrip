@pytest.mark.asyncio
async def test_supplement_cache_distinguishes_station_identity_service_date_and_anchor():
    from datetime import time
    from application.services.next_day_discovery import NextDayDiscoveryPolicy, NextDayRouteDiscovery
    provider, cache = AsyncMock(), FakeCacheAdapter()
    provider.search_routes.return_value = []
    discovery = NextDayRouteDiscovery(provider, cache)
    base = request().model_copy(update={'departure_station_id': 'origin', 'arrival_station_id': 'target'})
    await discovery.discover(base)
    await discovery.discover(base.model_copy(update={'departure_station': 'Cosmetic label'}))
    assert provider.search_routes.await_count == 1
    await discovery.discover(base.model_copy(update={'arrival_station_id': 'different-target'}))
    await discovery.discover(base.model_copy(update={'departure_date': '2026-11-05'}))
    await NextDayRouteDiscovery(provider, cache, policy=NextDayDiscoveryPolicy(time(6))).discover(base)
    assert provider.search_routes.await_count == 4


